"""
report_generator.py - Forensic & Audit Report Generation (PDF & TXT)
AI-Based Phishing Call Detection and Risk Analyzer
2nd-Year B.Tech CSE Cyber Security Mini-Project

Generates formal cybersecurity investigation reports in both PDF (via ReportLab)
and structured plain-text (TXT) formats for archival, academic submission, and reporting.
"""

import io
from datetime import datetime
from typing import Dict, Any, List

from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, KeepTogether, HRFlowable
)


def generate_txt_report(analysis_data: Dict[str, Any], filename: str = "Audio_Call_Recording") -> str:
    """
    Generates a clean, forensic-style ASCII formatted text report.
    """
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    score = analysis_data.get("risk_score", 0)
    level = analysis_data.get("risk_level", "LOW")
    indicators = analysis_data.get("indicators_detected", [])
    recommendations = analysis_data.get("safety_recommendations", [])
    transcript = analysis_data.get("transcript", "")
    breakdown = analysis_data.get("score_breakdown", {})
    synergy_exp = analysis_data.get("synergy_explanation", "None")

    border = "=" * 78
    sub_border = "-" * 78

    lines = [
        border,
        "   AI-BASED PHISHING CALL DETECTION AND RISK ANALYZER - INCIDENT REPORT",
        "                  Forensic Call Analysis & Threat Audit Report",
        border,
        f"Generated On       : {now_str}",
        f"Source File / Name : {filename}",
        f"Overall Risk Score : {score} / 100",
        f"Risk Level         : [{level.upper()}]",
        f"Indicators Flagged : {len(indicators)}",
        border,
        "",
        "1. EXECUTIVE RISK ASSESSMENT",
        sub_border,
    ]

    if level == "HIGH":
        lines.append("ASSESSMENT: CRITICAL THREAT DETECTED.")
        lines.append("The call contains classic vishing indicators including coercive urgency,")
        lines.append("credential harvesting, or unauthorized remote desktop commands.")
    elif level == "MEDIUM":
        lines.append("ASSESSMENT: SUSPICIOUS CALL DETECTED.")
        lines.append("The conversation exhibits abnormal social engineering patterns or financial pressure.")
    else:
        lines.append("ASSESSMENT: LOW RISK / LIKELY BENIGN.")
        lines.append("No critical phishing or credential theft patterns were detected.")

    lines.extend([
        "",
        f"Scoring Breakdown : Raw Sum = {breakdown.get('raw_sum', 0)} pts | Synergy Bonus = {breakdown.get('synergy_bonus', 0)} pts",
        f"Synergy Note      : {synergy_exp}",
        f"Final Risk Score  : {score}/100 (Capped at 100 max)",
        "",
        "2. DETECTED PHISHING INDICATORS & EVIDENCE",
        sub_border,
    ])

    if not indicators:
        lines.append("No suspicious indicators detected in this transcript.")
    else:
        for idx, ind in enumerate(indicators, 1):
            lines.append(f"[{idx}] {ind['name']} ({ind['category']})")
            lines.append(f"    Severity Level     : {ind['severity']} (+{ind['weight']} pts)")
            lines.append(f"    Why Dangerous      : {ind['why_dangerous']}")
            lines.append("    Forensic Excerpts  :")
            for exc in ind.get("excerpts", []):
                clean_exc = exc.replace("\n", " ").strip()
                lines.append(f'      * "{clean_exc}"')
            lines.append(f"    Action Item        : {ind['recommendation']}")
            lines.append("")

    lines.extend([
        "3. ACTIONABLE SAFETY RECOMMENDATIONS",
        sub_border,
    ])
    for idx, rec in enumerate(recommendations, 1):
        lines.append(f"{idx}. {rec}")

    lines.extend([
        "",
        "4. FULL CALL TRANSCRIPT",
        sub_border,
        transcript if transcript.strip() else "[No transcript provided]",
        "",
        border,
        "FORENSIC & ACADEMIC DISCLAIMER:",
        "This automated report is generated by a heuristic rule-based cybersecurity analysis",
        "engine for educational and screening purposes. It does not constitute legally",
        "binding evidence. In case of financial fraud, contact the national cyber hotline 1930.",
        border,
    ])

    return "\n".join(lines)


def generate_pdf_report(analysis_data: Dict[str, Any], filename: str = "Audio_Call_Recording") -> bytes:
    """
    Generates a publication-grade PDF report using ReportLab.
    
    Returns:
        bytes: Binary PDF data suitable for direct download.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()

    # Custom styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=4
    )

    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#64748b"),
        spaceAfter=12
    )

    h2_style = ParagraphStyle(
        "Heading2_Custom",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=10,
        spaceAfter=6
    )

    body_style = ParagraphStyle(
        "Body_Custom",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#334155")
    )

    excerpt_style = ParagraphStyle(
        "Excerpt_Custom",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#b91c1c")
    )

    disclaimer_style = ParagraphStyle(
        "Disclaimer_Custom",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=7.5,
        leading=10.5,
        textColor=colors.HexColor("#64748b")
    )

    story = []

    # Title & Header
    story.append(Paragraph("AI-Based Phishing Call Detection & Risk Analyzer", title_style))
    story.append(Paragraph("Forensic Call Analysis & Threat Intelligence Audit Report", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0284c7"), spaceAfter=10))

    score = analysis_data.get("risk_score", 0)
    level = analysis_data.get("risk_level", "LOW")
    now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    # Color mapping
    if level == "HIGH":
        banner_bg = colors.HexColor("#fee2e2")
        banner_border = colors.HexColor("#ef4444")
        banner_text_col = colors.HexColor("#991b1b")
    elif level == "MEDIUM":
        banner_bg = colors.HexColor("#fef3c7")
        banner_border = colors.HexColor("#f59e0b")
        banner_text_col = colors.HexColor("#92400e")
    else:
        banner_bg = colors.HexColor("#dcfce7")
        banner_border = colors.HexColor("#10b981")
        banner_text_col = colors.HexColor("#166534")

    # Metadata & Score Banner Table
    banner_data = [
        [
            Paragraph(f"<b>Case File:</b> {filename}<br/><b>Analyzed On:</b> {now_str}<br/><b>Engine:</b> Heuristic Vishing Rule Engine v2.0", body_style),
            Paragraph(
                f"<font size=11><b>RISK LEVEL</b></font><br/>"
                f"<font size=20><b>{level}</b></font><br/>"
                f"<font size=12>Score: <b>{score} / 100</b></font>",
                ParagraphStyle("ScoreBox", parent=styles["Normal"], alignment=1, textColor=banner_text_col)
            )
        ]
    ]

    banner_table = Table(banner_data, colWidths=[350, 182])
    banner_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, 0), colors.HexColor("#f8fafc")),
        ("BACKGROUND", (1, 0), (1, 0), banner_bg),
        ("BOX", (0, 0), (0, 0), 1, colors.HexColor("#cbd5e1")),
        ("BOX", (1, 0), (1, 0), 1.5, banner_border),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(banner_table)
    story.append(Spacer(1, 12))

    # Section 1: Detected Indicators Table
    story.append(Paragraph("1. Detected Phishing Indicators & Threat Breakdown", h2_style))
    indicators = analysis_data.get("indicators_detected", [])

    if not indicators:
        story.append(Paragraph("No suspicious indicators or social engineering patterns were detected.", body_style))
    else:
        table_rows = [
            [
                Paragraph("<b>Indicator Name</b>", body_style),
                Paragraph("<b>Category</b>", body_style),
                Paragraph("<b>Severity</b>", body_style),
                Paragraph("<b>Weight</b>", body_style),
            ]
        ]
        for ind in indicators:
            table_rows.append([
                Paragraph(ind["name"], body_style),
                Paragraph(ind["category"], body_style),
                Paragraph(f"<b>{ind['severity']}</b>", body_style),
                Paragraph(f"+{ind['weight']} pts", body_style),
            ])

        ind_table = Table(table_rows, colWidths=[200, 160, 90, 82])
        ind_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#94a3b8")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("PADDING", (0, 0), (-1, -1), 5),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        story.append(ind_table)

    story.append(Spacer(1, 10))

    # Section 2: Forensic Evidence & Excerpts
    if indicators:
        story.append(Paragraph("2. Forensic Evidence & Threat Quotes", h2_style))
        for ind in indicators:
            excerpts_str = "<br/>• ".join([f'"{e}"' for e in ind.get("excerpts", [])])
            evidence_text = (
                f"<b>{ind['name']}</b> ({ind['severity']}):<br/>"
                f"• {excerpts_str}<br/>"
                f"<i>Impact: {ind['why_dangerous']}</i>"
            )
            story.append(Paragraph(evidence_text, excerpt_style))
            story.append(Spacer(1, 4))

    story.append(Spacer(1, 6))

    # Section 3: Safety Recommendations
    story.append(Paragraph("3. Actionable Safety Recommendations", h2_style))
    recommendations = analysis_data.get("safety_recommendations", [])
    for rec in recommendations:
        story.append(Paragraph(f"• {rec}", body_style))
        story.append(Spacer(1, 3))

    story.append(Spacer(1, 10))

    # Section 4: Transcript Sample
    story.append(Paragraph("4. Call Transcript", h2_style))
    transcript_text = analysis_data.get("transcript", "")
    # Truncate if extremely long for PDF layout safety
    if len(transcript_text) > 1400:
        transcript_display = transcript_text[:1400] + "\n... [Transcript truncated for report summary length]"
    else:
        transcript_display = transcript_text if transcript_text else "[No transcript provided]"

    transcript_display_clean = transcript_display.replace("\n", "<br/>")
    transcript_box = Table(
        [[Paragraph(transcript_display_clean, ParagraphStyle("TranscriptStyle", parent=styles["Normal"], fontSize=8, leading=11, textColor=colors.HexColor("#1e293b")))]],
        colWidths=[532]
    )
    transcript_box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("PADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(transcript_box)
    story.append(Spacer(1, 12))

    # Disclaimer Footer
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceAfter=6))
    disclaimer_text = (
        "<b>FORENSIC & COMPLIANCE NOTICE:</b> This report is generated by a heuristic "
        "rule-based speech-to-text threat analyzer. It assists in detecting social "
        "engineering patterns but does not replace official law enforcement investigations. Emergency Helpline: 1930."
    )
    story.append(Paragraph(disclaimer_text, disclaimer_style))

    doc.build(story)
    pdf_bytes = buffer.getvalue()
    buffer.close()
    return pdf_bytes
